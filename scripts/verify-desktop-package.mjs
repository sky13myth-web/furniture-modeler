import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';

const require = createRequire(import.meta.url);
const asar = require('@electron/asar');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const archive = path.join(root, 'dist', 'win-unpacked', 'resources', 'app.asar');
const files = asar.listPackage(archive).map(file => file.replace(/\\/g, '/').replace(/^\//, ''));
const permitted = /^(?:index\.html|LICENSE(?:\.(?:ru|tr)\.md)?|package\.json|src(?:\/|\/.*\.(?:js|css))?|desktop(?:\/|\/[^/]+\.cjs)?|build(?:\/|\/icon\.ico)?|docs(?:\/|\/licenses(?:\/|\/MIT-through-v2\.2\.0\.txt)?)?)$/;
for (const file of files) assert.match(file, permitted, `Unexpected packaged file: ${file}`);
for (const file of ['index.html', 'src/app.js', 'src/studio.css', 'desktop/main.cjs', 'desktop/policy.cjs', 'desktop/preload.cjs', 'desktop/file-save.cjs', 'build/icon.ico', 'LICENSE','LICENSE.ru.md','LICENSE.tr.md','docs/licenses/MIT-through-v2.2.0.txt']) assert.ok(files.includes(file), `Missing packaged file: ${file}`);
const metadata = JSON.parse(asar.extractFile(archive, 'package.json').toString());
const sourceMetadata = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
assert.equal(metadata.version, sourceMetadata.version);
assert.equal(metadata.main, 'desktop/main.cjs');
assert.equal(metadata.license,'SEE LICENSE IN LICENSE');
for(const file of ['LICENSE','LICENSE.ru.md','LICENSE.tr.md','docs/licenses/MIT-through-v2.2.0.txt'])assert.ok(asar.extractFile(archive,file).equals(await readFile(path.join(root,file))),`Packaged license differs: ${file}`);
console.log(`Verified app.asar allowlist (${files.length} entries), application assets and version ${metadata.version}.`);
